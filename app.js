const APP_VERSION = 'v5.7';
const DB_NAME = 'GKenteiQuestionDB_v3';
const DB_VERSION = 1;
const STORE_NAME = 'questions';

function openDatabase() {
  return new Promise((resolve, reject) => {
    const req = indexedDB.open(DB_NAME, DB_VERSION);
    req.onupgradeneeded = (e) => {
      const db = e.target.result;
      if (!db.objectStoreNames.contains(STORE_NAME)) {
        db.createObjectStore(STORE_NAME, { keyPath: 'id' });
      }
    };
    req.onsuccess = () => resolve(req.result);
    req.onerror = () => reject(req.error);
  });
}

async function getAllFromDB() {
  const db = await openDatabase();
  return new Promise((resolve, reject) => {
    const tx = db.transaction(STORE_NAME, 'readonly');
    const store = tx.objectStore(STORE_NAME);
    const req = store.getAll();
    req.onsuccess = () => resolve(req.result);
    req.onerror = () => reject(req.error);
  });
}

async function saveAllToDB(items) {
  const db = await openDatabase();
  return new Promise((resolve, reject) => {
    const tx = db.transaction(STORE_NAME, 'readwrite');
    const store = tx.objectStore(STORE_NAME);
    store.clear();
    for (const item of items) {
      store.put(item);
    }
    tx.oncomplete = () => resolve();
    tx.onerror = () => reject(tx.error);
  });
}

// HTMLエスケープヘルパー
function escapeHtml(str) {
  if (str === null || str === undefined) return '';
  return String(str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#039;');
}

// 音声テキスト分割ユーティリティ（カラオケ式ハイライト＆TTSタイムアウト防止）
function splitSpeechText(text) {
  if (!text) return [];
  const rawParts = String(text).split(/([。！？\n]+)/);
  const sentences = [];
  let current = '';

  for (let i = 0; i < rawParts.length; i++) {
    const part = rawParts[i];
    if (!part) continue;
    if (/[。！？\n]+/.test(part)) {
      current += part;
      if (current.trim()) {
        sentences.push(current.trim());
      }
      current = '';
    } else {
      current += part;
    }
  }
  if (current.trim()) {
    sentences.push(current.trim());
  }

  // 1文が長い場合（55文字超）は読点でも分割して視認性と追従性を向上
  const finalChunks = [];
  sentences.forEach((s) => {
    if (s.length > 55) {
      const subParts = s.split(/([、，]+)/);
      let subCurrent = '';
      for (let j = 0; j < subParts.length; j++) {
        const sp = subParts[j];
        if (!sp) continue;
        if (/[、，]+/.test(sp)) {
          subCurrent += sp;
          if (subCurrent.length > 28) {
            finalChunks.push(subCurrent.trim());
            subCurrent = '';
          }
        } else {
          subCurrent += sp;
        }
      }
      if (subCurrent.trim()) finalChunks.push(subCurrent.trim());
    } else {
      finalChunks.push(s);
    }
  });

  return finalChunks.length > 0 ? finalChunks : [String(text)];
}

// 最適な日本語音声（Kyoko / O-Ren / Google 日本語 / Nanami 等）を選択するヘルパー
let cachedJaVoice = null;
function getPreferredJapaneseVoice() {
  if (!('speechSynthesis' in window)) return null;
  if (cachedJaVoice) return cachedJaVoice;
  const voices = window.speechSynthesis.getVoices() || [];
  const jaVoices = voices.filter(v => v.lang && (v.lang.startsWith('ja') || v.lang.includes('JP')));
  if (jaVoices.length === 0) return null;

  const priorityNames = ['O-Ren', 'Kyoko', 'Otoya', 'Google 日本語', 'Nanami', 'Haruka', 'Hattori'];
  for (const name of priorityNames) {
    const found = jaVoices.find(v => v.name && v.name.includes(name));
    if (found) {
      cachedJaVoice = found;
      return found;
    }
  }
  cachedJaVoice = jaVoices.find(v => v.default) || jaVoices[0];
  return cachedJaVoice;
}
if ('speechSynthesis' in window && 'onvoiceschanged' in window.speechSynthesis) {
  window.speechSynthesis.onvoiceschanged = () => {
    cachedJaVoice = null;
    getPreferredJapaneseVoice();
  };
}

