// G検定専門用語・数式・記号の完全日本語発音補正（画面表示は元の漢字・英字を維持）
function sanitizeForSpeech(text) {
  if (!text) return '';
  let s = String(text)
    // 開発用インデックス注記や絵文字を除去
    .replace(/（インデックス\d+）/g, '')
    .replace(/[🟢🚨💡🎯⏱️⚡🧠🏆📚🔢🎧👀⭐✓✕]/g, '')
    // 全角英字補正
    .replace(/ＸＡＩ/gi, 'エックスエーアイ')
    .replace(/ＡＩ/g, 'エーアイ')
    // 解説フォーマット記号の自然な日本語化
    .replace(/【正解：(\d+)（不適切）】/g, '正解は $1番、不適切なものを選ぶ問題です。')
    .replace(/【正解：(\d+)】/g, '正解は $1番。')
    .replace(/■\s*選択肢(\d+)（正解）：/g, '選択肢$1番が正解です。')
    .replace(/■\s*選択肢(\d+)（誤り＝正解）：/g, '選択肢$1番が誤りの記述であり、本問の正解です。')
    .replace(/■\s*選択肢(\d+)・(\d+)（誤り）：/g, '選択肢$1番と$2番は誤りです。')
    .replace(/■\s*選択肢(\d+)（誤り）：/g, '選択肢$1番は誤りです。')
    .replace(/■\s*選択肢(\d+)（適切）：/g, '選択肢$1番は適切な記述です。')
    .replace(/【体系的リレーション】/g, '体系的リレーション。')
    .replace(/【解説（([^】]+)）】/g, '$1 の解説。')
    .replace(/【([^】]+)】/g, '、$1、')
    .replace(/[■●◆▼▲★◎]/g, '。')
    .replace(/①/g, '1番、').replace(/②/g, '2番、').replace(/③/g, '3番、').replace(/④/g, '4番、');

  // 1. 数式・複合英語フレーズの置換
  for (let i = 0; i < SPEECH_PHRASE_DICT.length; i++) {
    const [target, replacement] = SPEECH_PHRASE_DICT[i];
    if (s.includes(target)) {
      s = s.split(target).join(replacement);
    }
  }

  // 2. 掛け算（3×3、3x3、224x224x3 など）を「かける」に置換
  s = s
    .replace(/(\d+)\s*[×x]\s*(\d+)\s*[×x]\s*(\d+)/g, '$1 かける $2 かける $3')
    .replace(/(\d+)\s*[×x]\s*(\d+)/g, '$1 かける $2')
    .replace(/×/g, ' かける ');

  // 3. ギリシャ文字・数学記号の日本語読み置換
  s = s
    .replace(/α/g, 'アルファ')
    .replace(/β/g, 'ベータ')
    .replace(/γ/g, 'ガンマ')
    .replace(/δ/g, 'デルタ')
    .replace(/Δ/g, 'デルタ')
    .replace(/ε/g, 'イプシロン')
    .replace(/η/g, 'イータ')
    .replace(/θ/g, 'シータ')
    .replace(/λ/g, 'ラムダ')
    .replace(/μ/g, 'ミュー')
    .replace(/π/g, 'パイ')
    .replace(/ρ/g, 'ロー')
    .replace(/σ/g, 'シグマ')
    .replace(/[Σ∑]/g, 'シグマ')
    .replace(/τ/g, 'タウ')
    .replace(/φ/g, 'ファイ')
    .replace(/[ωΩ]/g, 'オメガ')
    .replace(/√/g, 'ルート ')
    .replace(/≦/g, ' しょうなりイコール ')
    .replace(/≧/g, ' だいなりイコール ')
    .replace(/≪/g, ' じゅうぶんしょうなり ')
    .replace(/∈/g, ' ぞくする ')
    .replace(/∩/g, ' かつ ')
    .replace(/∪/g, ' または ')
    .replace(/→/g, ' から ');

  // 4. 誤読しやすい漢字熟語・専門用語の読み補正
  for (let i = 0; i < SPEECH_KANJI_DICT.length; i++) {
    const [kanji, reading] = SPEECH_KANJI_DICT[i];
    if (s.includes(kanji)) {
      s = s.split(kanji).join(reading);
    }
  }

  // 5. 英単語・AI略語のカタカナ発音補正
  s = s.replace(/(?<![A-Za-z])([A-Za-z][A-Za-z0-9]*)(?![A-Za-z])/g, (match) => {
    return SPEECH_WORD_MAP[match] || match;
  });

  // 6. カタカナ語＋単漢字接尾辞（〜下、〜上、〜内、〜間、〜数、〜時、〜値、〜法、〜則、〜等 など）の誤読防止
  s = s
    .replace(/([ァ-ヶー]+)下(?![げが])/g, '$1か')
    .replace(/([ァ-ヶー]+)上(?![げが])/g, '$1じょう')
    .replace(/([ァ-ヶー]+)内/g, '$1ない')
    .replace(/([ァ-ヶー]+)間/g, '$1かん')
    .replace(/([ァ-ヶー]+)数/g, '$1すう')
    .replace(/([ァ-ヶー]+)時/g, '$1じ')
    .replace(/([ァ-ヶー]+)項/g, '$1こう')
    .replace(/([ァ-ヶー]+)名/g, '$1めい')
    .replace(/([ァ-ヶー]+)則/g, '$1そく')
    .replace(/([ァ-ヶー]+)法/g, '$1ほう')
    .replace(/([ァ-ヶー]+)比/g, '$1ひ')
    .replace(/([ァ-ヶー]+)状/g, '$1じょう')
    .replace(/([ァ-ヶー]+)型/g, '$1がた')
    .replace(/([ァ-ヶー]+)層/g, '$1そう')
    .replace(/([ァ-ヶー]+)値/g, '$1ち')
    .replace(/([ァ-ヶー]+)率/g, '$1りつ')
    .replace(/([ァ-ヶー]+)度/g, '$1ど')
    .replace(/([ァ-ヶー]+)側/g, '$1がわ')
    .replace(/([ァ-ヶー]+)氏/g, '$1し')
    .replace(/([ァ-ヶー]+)役/g, '$1やく')
    .replace(/([ァ-ヶー]+)点/g, '$1てん')
    .replace(/([ァ-ヶー]+)化/g, '$1か')
    .replace(/([ァ-ヶー]+)量/g, '$1りょう')
    .replace(/([ァ-ヶー]+)解/g, '$1かい')
    .replace(/([ァ-ヶー]+)期/g, '$1き')
    .replace(/([ァ-ヶー]+)性/g, '$1せい')
    .replace(/([ァ-ヶー]+)系/g, '$1けい')
    .replace(/([ァ-ヶー]+)後/g, '$1ご')
    .replace(/([ァ-ヶー]+)死/g, '$1し')
    .replace(/(?<![同均平一高対])等(?![しいしくしさ級分価])/g, 'など');

  // 7. 括弧やスラッシュの読み上げリズム調整＆同一読み重複（例: ドロップアウト（Dropout））の解消
  s = s
    .replace(/\s*\/\s*/g, '、')
    .replace(/[（(]/g, '、')
    .replace(/[）)]/g, '、')
    .replace(/、{2,}/g, '、')
    .replace(/([ぁ-んァ-ヶー]{2,25})\s*、\s*\1/g, '$1')
    .replace(/、{2,}/g, '、')
    .replace(/。{2,}/g, '。');

  return s.trim();
}

